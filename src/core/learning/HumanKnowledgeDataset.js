/**
 * Returns total tokens and dataset summary metrics
 */
export const getDatasetMetrics = () => {
  let totalTokens = 0;
  let totalRecords = 0;
  const categories = [];

  for (const [key, cat] of Object.entries(HUMAN_KNOWLEDGE_DATASET)) {
    totalTokens += cat.tokensCount || 0;
    totalRecords += cat.records.length;
    categories.push({
      key,
      name: cat.category,
      tokens: cat.tokensCount,
      recordsCount: cat.records.length
    });
  }

  return {
    totalTokens,
    totalRecords,
    categories,
    version: '4.2-Vast-Universal-Human-Corpus'
  };
};

/**
 * Semantic keyword lookup across the entire dataset
 */
export const queryHumanKnowledge = (queryStr) => {
  if (!queryStr || typeof queryStr !== 'string') return [];
  const q = queryStr.toLowerCase();
  const results = [];

  for (const [catKey, cat] of Object.entries(HUMAN_KNOWLEDGE_DATASET)) {
    for (const rec of cat.records) {
      if (
        rec.concept.toLowerCase().includes(q) ||
        rec.insight.toLowerCase().includes(q) ||
        rec.guardianshipLesson.toLowerCase().includes(q)
      ) {
        results.push({ ...rec, category: cat.category, categoryKey: catKey });
      }
    }
  }

  return results;
};
